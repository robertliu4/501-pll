"""Ring VCO feasibility on GF180 3.3 V devices, across corners.

A) speed headroom: plain 5-stage inverter ring, and the starved ring with the
   starve devices fully on (the fastest the starved topology can go)
B) starved ring with an ideal reference current: f vs I, gives C_L and df/dI
C) full VCO: degenerated V-to-I converter + minimum current I0, sweep Vctrl,
   gives the tuning curve and K_VCO at every corner
Outputs: results/vco_*.png, results/vco_summary.txt
"""
import itertools
from concurrent.futures import ThreadPoolExecutor

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import spice

NSTAGE = 5
# first-pass sizes (um). Switches minimum-ish, starve devices long-ish and wide.
SZ = dict(WNI=2.0, WPI=5.0, LI=0.28, WNS=10.0, LNS=0.5, WPS=30.0, LPS=0.5,
          WM1=20.0, LM1=1.0)
F_TARGET = 300e6
K_TARGET = 200e6      # Hz/V, the system-level number from the loop design


def stage_subckts():
    s = SZ
    return f"""
.subckt inv in out vdd vss
MP out in vdd vdd pfet_03v3 W={s['WPI']}u L={s['LI']}u
MN out in vss vss nfet_03v3 W={s['WNI']}u L={s['LI']}u
.ends
.subckt sstage in out vbp vbn vdd vss
MPS xp vbp vdd vdd pfet_03v3 W={s['WPS']}u L={s['LPS']}u
MPI out in xp vdd pfet_03v3 W={s['WPI']}u L={s['LI']}u
MNI out in xn vss nfet_03v3 W={s['WNI']}u L={s['LI']}u
MNS xn vbn vss vss nfet_03v3 W={s['WNS']}u L={s['LNS']}u
.ends
"""


def ring(kind):
    """5-stage ring on nodes n1..n5. Every node also carries one inverter's worth of
    gate capacitance: the output buffer on n5, matching dummies elsewhere."""
    lines = []
    for k in range(NSTAGE):
        a, b = f"n{k+1}", f"n{(k+1) % NSTAGE + 1}"
        if kind == "plain":
            lines.append(f"X{k} {a} {b} vdd 0 inv")
        else:
            lines.append(f"X{k} {a} {b} vbp vbn vdd 0 sstage")
        # gate-only dummy load = the output buffer's input capacitance, no crowbar current
        lines.append(f"MDP{k} vdd {b} vdd vdd pfet_03v3 W={SZ['WPI']}u L={SZ['LI']}u")
        lines.append(f"MDN{k} 0 {b} 0 0 nfet_03v3 W={SZ['WNI']}u L={SZ['LI']}u")
    return "\n".join(lines)


def measure_freq(name, corner_key, body, tstop=200e-9):
    corner, temp, vdd = spice.CORNERS[corner_key]
    deck = f"""* {name}
{spice.models(corner, mim=False)}
.temp {temp}
.param vddv={vdd}
VDD vdd 0 {vdd}
{stage_subckts()}
{body}
{ring('starved' if 'vbp' in body or 'vbn' in body else 'plain')}
.ic v(n1)=0 v(n2)={vdd} v(n3)=0 v(n4)={vdd}
.control
tran 10p {tstop}
meas tran ta WHEN v(n5)={vdd/2} RISE=4
meas tran tb WHEN v(n5)={vdd/2} RISE=12
meas tran ivdd AVG i(VDD) FROM=ta TO=tb
.endc
.end
"""
    log = spice.run(name, deck)
    m = spice.meas(log)
    if "ta" in m and "tb" in m and m["tb"] > m["ta"]:
        f = 8 / (m["tb"] - m["ta"])
        return f, -m.get("ivdd", np.nan)
    return np.nan, np.nan


def bias_ideal(iref):
    # Iref into NMOS diode (vbn); NMOS mirror pulls the same current out of the PMOS diode (vbp)
    s = SZ
    return f"""
IREF vdd vbn {iref}
M4 vbn vbn 0 0 nfet_03v3 W={s['WNS']}u L={s['LNS']}u
M3 vbp vbn 0 0 nfet_03v3 W={s['WNS']}u L={s['LNS']}u
M2 vbp vbp vdd vdd pfet_03v3 W={s['WPS']}u L={s['LPS']}u
"""


def bias_v2i(vctrl, rs, i0):
    # Vctrl -> M1 (source-degenerated by Rs) plus floor current I0, both into the PMOS diode M2;
    # M3 (PMOS mirror) feeds the NMOS diode M4 that sets vbn
    s = SZ
    return f"""
VCTRL vc 0 {vctrl}
M1 vbp vc s1 0 nfet_03v3 W={s['WM1']}u L={s['LM1']}u
RS s1 0 {rs}
I0 vbp 0 {i0}
M2 vbp vbp vdd vdd pfet_03v3 W={s['WPS']}u L={s['LPS']}u
M3 vbn vbp vdd vdd pfet_03v3 W={s['WPS']}u L={s['LPS']}u
M4 vbn vbn 0 0 nfet_03v3 W={s['WNS']}u L={s['LNS']}u
"""


def main():
    keys = list(spice.CORNERS)
    out = []
    pool = ThreadPoolExecutor(max_workers=10)

    # A) speed headroom
    fa = {}
    jobs = {}
    for ck in keys:
        corner, temp, vdd = spice.CORNERS[ck]
        jobs[("plain", ck)] = pool.submit(measure_freq, f"ringA_plain_{ck}", ck, "* plain ring")
        jobs[("full", ck)] = pool.submit(measure_freq, f"ringA_full_{ck}", ck,
                                         f"Vbp vbp 0 0\nVbn vbn 0 {vdd}")
    for (kind, ck), j in jobs.items():
        fa[(kind, ck)] = j.result()[0]
    out.append("A) speed headroom (MHz): corner, plain ring, starved ring with starve devices fully on")
    for ck in keys:
        out.append(f"   {ck:12s} {fa[('plain', ck)]/1e6:8.1f} {fa[('full', ck)]/1e6:8.1f}")

    # B) f vs ideal I
    irefs = np.array([10, 20, 40, 60, 80, 100, 130, 160, 200, 250, 300]) * 1e-6
    fb = {}
    jobs = {(ck, i): pool.submit(measure_freq, f"ringB_{ck}_{i*1e6:.0f}u", ck, bias_ideal(i))
            for ck in keys for i in irefs}
    for (ck, i), j in jobs.items():
        fb[(ck, i)] = j.result()
    out.append("\nB) starved ring, ideal Iref: f (MHz) / supply current (uA)")
    out.append("   I(uA)  " + " ".join(f"{ck:>16s}" for ck in keys))
    for i in irefs:
        out.append(f"   {i*1e6:5.0f}  " + " ".join(f"{fb[(ck, i)][0]/1e6:8.1f}/{fb[(ck, i)][1]*1e6:6.0f}" for ck in keys))
    # effective C_L from the low-current slope at typical: f = I/(N C_L VDD)
    ft = np.array([fb[("tt_27C_3v3", i)][0] for i in irefs])
    lo = (irefs <= 100e-6) & np.isfinite(ft)
    slope = np.polyfit(irefs[lo], ft[lo], 1)[0]
    cl = 1 / (NSTAGE * 3.3 * slope)
    fin = np.isfinite(ft)
    i_at_target = np.interp(F_TARGET, ft[fin], irefs[fin])
    dfdi = np.interp(i_at_target, irefs[fin], np.gradient(ft[fin], irefs[fin]))
    out.append(f"   typical: df/dI = {slope/1e12:.2f} MHz/uA at low current -> effective C_L = {cl*1e15:.1f} fF/stage")
    out.append(f"   typical: {F_TARGET/1e6:.0f} MHz needs I = {i_at_target*1e6:.0f} uA; local df/dI = {dfdi/1e12:.2f} MHz/uA")

    # C) full VCO with V-to-I. Pick Rs so dI/dVctrl * df/dI ~= K_TARGET (gm1*Rs >> 1 assumed),
    # and I0 so the floor frequency is about half the target.
    rs = dfdi / K_TARGET
    i0 = float(np.interp(F_TARGET / 2, ft[fin], irefs[fin]))
    vcs = np.round(np.arange(0.0, 3.31, 0.15), 3)
    fc = {}
    jobs = {(ck, v): pool.submit(measure_freq, f"vcoC_{ck}_{v:.2f}", ck, bias_v2i(v, rs, i0))
            for ck in keys for v in vcs}
    for (ck, v), j in jobs.items():
        fc[(ck, v)] = j.result()[0]
    out.append(f"\nC) full VCO: Rs = {rs/1e3:.1f} kOhm, I0 = {i0*1e6:.0f} uA (ideal R and I0 for now)")
    out.append("   Vctrl  " + " ".join(f"{ck:>12s}" for ck in keys))
    for v in vcs:
        out.append(f"   {v:5.2f}  " + " ".join(f"{fc[(ck, v)]/1e6:12.1f}" for ck in keys))
    lock = {}
    for ck in keys:
        f = np.array([fc[(ck, v)] for v in vcs])
        k = np.gradient(f, vcs)
        good = np.isfinite(f)
        if np.nanmax(f) >= F_TARGET >= np.nanmin(f):
            # first crossing of the target on the rising part of the curve
            idx = np.where(good[:-1] & (f[:-1] <= F_TARGET) & (f[1:] > F_TARGET))[0]
            if len(idx):
                i = idx[0]
                vl = vcs[i] + (F_TARGET - f[i]) / (f[i+1] - f[i]) * (vcs[i+1] - vcs[i])
                kl = np.interp(vl, vcs, k)
                lock[ck] = (vl, kl)
    out.append("   lock point for 300 MHz (Vctrl, K_VCO at that point):")
    for ck in keys:
        if ck in lock:
            out.append(f"   {ck:12s} Vctrl = {lock[ck][0]:.2f} V, K_VCO = {lock[ck][1]/1e6:.0f} MHz/V")
        else:
            out.append(f"   {ck:12s} 300 MHz NOT reachable")

    # D) supply pushing at typical, Vctrl at the typical lock point
    if "tt_27C_3v3" in lock:
        vl = lock["tt_27C_3v3"][0]
        fp = []
        for vdd in (3.2, 3.3, 3.4):
            spice.CORNERS["tmp"] = ("typical", 27, vdd)
            fp.append(measure_freq(f"vcoD_push_{vdd}", "tmp", bias_v2i(vl, rs, i0))[0])
        del spice.CORNERS["tmp"]
        push = (fp[2] - fp[0]) / 0.2
        out.append(f"\nD) supply pushing at Vctrl = {vl:.2f} V: {push/1e6:.0f} MHz/V "
                   f"({push/fp[1]*100:.0f} %/V); 10 mV of supply noise = {push*0.01/1e6:.2f} MHz")

    txt = "\n".join(out)
    print(txt)
    (spice.RESULTS / "vco_summary.txt").write_text(txt + "\n\nsizes (um): " + str(SZ) + "\n")

    fig, ax = plt.subplots(1, 2, figsize=(12, 4.5))
    for ck in keys:
        ax[0].plot(irefs * 1e6, [fb[(ck, i)][0] / 1e6 for i in irefs], "o-", ms=3, label=ck)
        ax[1].plot(vcs, [fc[(ck, v)] / 1e6 for v in vcs], "o-", ms=3, label=ck)
    ax[0].set(xlabel="I_ref (uA)", ylabel="f (MHz)", title="Starved 5-stage ring, ideal bias current")
    ax[1].axhline(F_TARGET / 1e6, color="k", ls=":", lw=1)
    ax[1].axvspan(1.0, 2.7, color="g", alpha=0.08, label="CP window (assumed)")
    ax[1].set(xlabel="Vctrl (V)", ylabel="f (MHz)",
              title=f"VCO tuning curve, Rs={rs/1e3:.1f}k, I0={i0*1e6:.0f}uA")
    for a in ax:
        a.grid(alpha=0.3)
        a.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(spice.RESULTS / "vco_tuning.png", dpi=130)


if __name__ == "__main__":
    main()
