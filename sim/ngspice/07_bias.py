"""Bias reference feasibility: constant-gm (beta-multiplier) with a ppolyf_u_1k resistor.

  I = 2 / (mu_n Cox (W/L)_1 R^2) * (1 - 1/sqrt(K))^2      (square law, K = 4)

Sizes R so the reference gives 10 uA at typical (mirrored x4 to I_cp = 40 uA
later), then reports the spread across MOS/resistor corners, temperature and
supply. The loop tolerates 0.5-2x in I_cp*K_vco, so roughly +-30 % is fine.
A startup circuit is still needed in the real design; here .nodeset picks the
wanted operating point.
Output: results/bias.txt
"""
import numpy as np

import spice

W1, L1, K = 10.0, 2.0, 4
WP, LP = 20.0, 2.0
RW = 2.0          # um, resistor width (HRES min is 1 um)
CASES = {
    "tt_27C_3v3": ("typical", 27, 3.3),
    "ss_85C_3v0": ("ss", 85, 3.0),
    "ff_0C_3v6": ("ff", 0, 3.6),
    "sf_27C_3v3": ("sf", 27, 3.3),
    "fs_27C_3v3": ("fs", 27, 3.3),
    "tt_0C_3v3": ("typical", 0, 3.3),
    "tt_85C_3v3": ("typical", 85, 3.3),
    "tt_27C_3v0": ("typical", 27, 3.0),
    "tt_27C_3v6": ("typical", 27, 3.6),
}


def ibias(case, rlen):
    corner, temp, vdd = CASES[case]
    deck = f"""* beta multiplier {case} rlen={rlen}
{spice.models(corner, mim=False, res=True)}
.temp {temp}
VDD vdd 0 {vdd}
* NMOS pair: M1 diode, M2 = K x M1 degenerated by R
M1 n1 n1 0 0 nfet_03v3 W={W1}u L={L1}u
M2 n2 n1 s2 0 nfet_03v3 W={W1}u L={L1}u m={K}
XR s2 0 0 ppolyf_u_1k r_width={RW}e-6 r_length={rlen}e-6
* PMOS mirror: M3 diode on the M2 side, M4 copies into M1
M3 n2 n2 vdd vdd pfet_03v3 W={WP}u L={LP}u
M4 n1 n2 vdd vdd pfet_03v3 W={WP}u L={LP}u
VM vdd vm 0
M5 out n2 vm vdd pfet_03v3 W={WP}u L={LP}u
VOUT out 0 1.0
.nodeset v(n1)=0.8 v(n2)={vdd-1.0}
.control
op
let ib = i(VM)
print ib
.endc
.end
"""
    m = spice.meas(spice.run(f"bias_{case}_{rlen:.1f}", deck))
    return m.get("ib", np.nan)


def main():
    # size R for 10 uA at typical (bisection on resistor length; I falls as R grows)
    lo, hi = 1.0, 60.0
    for _ in range(25):
        mid = 0.5 * (lo + hi)
        if ibias("tt_27C_3v3", mid) > 10e-6:
            lo = mid
        else:
            hi = mid
    rlen = 0.5 * (lo + hi)
    lines = [f"beta multiplier, M1 {W1}/{L1} um, K = {K}, R = ppolyf_u_1k {RW} um x {rlen:.1f} um "
             f"(~{rlen/RW:.1f} squares)"]
    base = ibias("tt_27C_3v3", rlen)
    for c in CASES:
        i = ibias(c, rlen)
        lines.append(f"  {c:12s} I = {i*1e6:6.2f} uA  ({(i/base-1)*100:+5.1f} %)")
    txt = "\n".join(lines)
    print(txt)
    (spice.RESULTS / "bias.txt").write_text(txt + "\n")


if __name__ == "__main__":
    main()
